export const getCitiesByState = (state) => {
  if (!state || state === 'All' || state === 'All India' || state === 'Central') return [];
  return STATE_CITIES[state] || [];
};

/**
 * Determines whether a citizen profile contains all required demographic parameters
 * for scheme eligibility calculation.
 */
export const checkProfileCompleteness = (user) => {
  if (!user) return false;

  // 1. Full Name
  if (!user.name || typeof user.name !== 'string' || !user.name.trim()) return false;

  // 2. Mobile Number (mobileNumber or phone)
  const mobile = user.mobileNumber || user.phone;
  if (!mobile || typeof mobile !== 'string' || !mobile.trim()) return false;

  // 3. Age (whole number between 1 and 120)
  const age = Number(user.age);
  if (user.age === undefined || user.age === null || user.age === '' || isNaN(age) || !Number.isInteger(age) || age < 1 || age > 120) {
    return false;
  }

  // 4. Gender
  if (!user.gender || typeof user.gender !== 'string' || !user.gender.trim()) return false;

  // 5. Annual Income (non-negative number)
  const income = Number(user.annualIncome);
  if (user.annualIncome === undefined || user.annualIncome === null || user.annualIncome === '' || isNaN(income) || income < 0) {
    return false;
  }

  // 6. State of Residence
  if (!user.state || typeof user.state !== 'string' || !user.state.trim() || user.state.toLowerCase() === 'all') {
    return false;
  }

  // 7. City
  if (!user.city || typeof user.city !== 'string' || !user.city.trim()) {
    return false;
  }

  // 8. Occupation
  if (!user.occupation || typeof user.occupation !== 'string' || !user.occupation.trim() || user.occupation.toLowerCase() === 'all') {
    return false;
  }

  // 9. Education Level
  if (!user.education || typeof user.education !== 'string' || !user.education.trim() || user.education.toLowerCase() === 'all') {
    return false;
  }

  // 10. Social Category / Caste
  if (!user.caste || typeof user.caste !== 'string' || !user.caste.trim() || user.caste.toLowerCase() === 'all') {
    return false;
  }

  return true;
};
